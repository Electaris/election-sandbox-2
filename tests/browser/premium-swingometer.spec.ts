import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
  test(`Swingometer editor and contributor navigation at ${viewport.width}`, async ({ page }) => {
    test.setTimeout(90_000);
    await page.setViewportSize(viewport);
    await page.goto("/app/");
    await page.getByRole("button", { name: "Pennsylvania", exact: true }).first().click();
    await expect(page.getByRole("button", { name: "Copy scenario link" })).toBeEnabled({ timeout: 30_000 });
    await page.getByRole("button", { name: "expanded", exact: true }).click();
    await page.getByRole("tab", { name: "Behavior", exact: true }).click();
    const operations = page.getByRole("group", { name: "Behavior operation", exact: true });
    await operations.getByRole("button", { name: "Preference", exact: true }).click();
    const explanation = page.locator(".operation-details");
    await expect(explanation.locator(".model-contract-grid")).toBeHidden();
    await explanation.locator("summary").focus();
    await page.keyboard.press("Enter");
    await expect(explanation.locator(".model-contract-grid")).toBeVisible();
    await expect(explanation).toContainText("Total ballots and all third-party totals stay fixed");
    await page.keyboard.press("Space");
    await expect(explanation.locator(".model-contract-grid")).toBeHidden();
    const transfer = page.getByRole("slider", { name: "Two-party preference transfer", exact: true });
    await transfer.fill("2.5");
    await expect(page.getByRole("button", { name: "Copy scenario link" })).toBeEnabled();
    const recipe = page.url();
    await page.getByRole("button", { name: "Collapse behavior editor" }).click();
    await expect(transfer).toBeHidden();
    await expect(page.getByRole("button", { name: "Expand behavior editor" })).toHaveAttribute("aria-expanded", "false");
    await page.getByRole("button", { name: "Expand behavior editor" }).press("Enter");
    await expect(transfer).toHaveValue("2.5");
    expect(page.url()).toBe(recipe);
    expect(await operations.getByRole("button", { name: "Preference", exact: true }).evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThanOrEqual(viewport.width < 800 ? 44 : 36);
    const folder = resolve("docs/review/v0.31c-swingometer/screenshots");
    mkdirSync(folder, { recursive: true });
    await page.screenshot({ path: resolve(folder, `editor-${viewport.width}.png`) });
    await page.getByRole("tab", { name: "Contributors", exact: true }).click();
    const view = page.getByRole("group", { name: "Contribution view", exact: true });
    await view.getByRole("button", { name: "Movement", exact: true }).click();
    const geography = page.getByRole("group", { name: "Contribution geography", exact: true });
    await geography.getByRole("button", { name: "Counties", exact: true }).click();
    await page.getByRole("group", { name: "Contribution operation", exact: true }).getByRole("button", { name: "Preference", exact: true }).click();
    const rows = page.locator(".contribution-list li > button");
    await expect(rows.first()).toBeVisible();
    await rows.first().focus();
    await page.keyboard.press("ArrowDown");
    await expect(rows.nth(1)).toBeFocused();
    const countyName = await rows.nth(1).locator(".contribution-name strong").innerText();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("region", { name: `Data inspector for ${countyName}`, exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Contributors", exact: true }).click();
    await expect(page.locator('.contribution-list button[aria-current="location"]')).toContainText(countyName);
    await view.getByRole("button", { name: "Result structure", exact: true }).click();
    await expect(page.locator(".contribution-structure-comparison")).toBeVisible();
    await expect(geography.getByRole("button", { name: "Counties", exact: true })).toHaveAttribute("aria-pressed", "true");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.screenshot({ path: resolve(folder, `contributors-${viewport.width}.png`) });
  });
}
